function run_cellreg_case(case_dir, alignment_type, out_file, microns_per_pixel)
% Headless CellReg (zivlab/CellReg v1.6.0) on one benchmark case, following
% CellReg/demo_2P.m without figures.
% case_dir: folder with session_1.mat, session_2.mat, ... each holding a sparse
%   matrix A (n_roi x Ly*Lx, column index y*Lx+x, 0-based C order) and dims [Ly Lx].
% alignment_type: 'Translations and Rotations' or 'Non-rigid'.
% Saves out_file with cell_to_index_map (n_cells x n_sessions, 1-based ROI
% index, 0 = absent), the chosen model and CellReg's estimated accuracy.

files = dir(fullfile(case_dir, 'session_*.mat'));
[~, order] = sort(cellfun(@(f) sscanf(f, 'session_%d.mat'), {files.name}));
files = files(order);
n_sessions = numel(files);
spatial_footprints = cell(1, n_sessions);
for s = 1:n_sessions
    d = load(fullfile(case_dir, files(s).name));
    Ly = double(d.dims(1)); Lx = double(d.dims(2));
    F = full(d.A);                                   % n x (Ly*Lx), C order
    F = permute(reshape(F, [size(F, 1), Lx, Ly]), [1 3 2]);  % n x Ly x Lx
    spatial_footprints{s} = F ./ max(max(F, [], 2), [], 3);
end

use_parallel_processing = ~isempty(ver('parallel'));
maximal_rotation = 30;
transformation_smoothness = 2;
reference_session_index = 1;
sufficient_correlation_centroids = 0.2;
sufficient_correlation_footprints = 0.3;
maximal_distance = 12;  % um
normalized_maximal_distance = maximal_distance / microns_per_pixel;
p_same_certainty_threshold = 0.95;
p_same_threshold = 0.5;

normalized_spatial_footprints = normalize_spatial_footprints(spatial_footprints);
[adjusted_spatial_footprints, adjusted_FOV, ~, ~, ~] = adjust_FOV_size(normalized_spatial_footprints);
adjusted_footprints_projections = compute_footprints_projections(adjusted_spatial_footprints);
centroid_locations = compute_centroid_locations(adjusted_spatial_footprints, microns_per_pixel);
centroid_projections = compute_centroids_projections(centroid_locations, adjusted_spatial_footprints);

if strcmp(alignment_type, 'Non-rigid')
    [spatial_footprints_corrected, centroid_locations_corrected, ~, ~, ~, alignment_translations, overlapping_FOV] = ...
        align_images(adjusted_spatial_footprints, centroid_locations, adjusted_footprints_projections, ...
        centroid_projections, adjusted_FOV, microns_per_pixel, reference_session_index, alignment_type, ...
        sufficient_correlation_centroids, sufficient_correlation_footprints, use_parallel_processing, ...
        transformation_smoothness);
else
    [spatial_footprints_corrected, centroid_locations_corrected, ~, ~, ~, alignment_translations, overlapping_FOV] = ...
        align_images(adjusted_spatial_footprints, centroid_locations, adjusted_footprints_projections, ...
        centroid_projections, adjusted_FOV, microns_per_pixel, reference_session_index, alignment_type, ...
        sufficient_correlation_centroids, sufficient_correlation_footprints, use_parallel_processing, ...
        maximal_rotation);
end

[number_of_bins, centers_of_bins] = estimate_number_of_bins(adjusted_spatial_footprints, normalized_maximal_distance);
[all_to_all_indexes, all_to_all_spatial_correlations, all_to_all_centroid_distances, ...
    neighbors_spatial_correlations, neighbors_centroid_distances, ~, ~, ~, ~, ~, ~] = ...
    compute_data_distribution(spatial_footprints_corrected, centroid_locations_corrected, normalized_maximal_distance);
[~, p_same_given_centroid_distance, ~, centroid_distances_model_same_cells, ...
    centroid_distances_model_different_cells, ~, MSE_centroid_distances_model, centroid_distance_intersection] = ...
    compute_centroid_distances_model(neighbors_centroid_distances, microns_per_pixel, centers_of_bins);
[~, p_same_given_spatial_correlation, ~, spatial_correlations_model_same_cells, ...
    spatial_correlations_model_different_cells, ~, MSE_spatial_correlations_model, spatial_correlation_intersection] = ...
    compute_spatial_correlations_model(neighbors_spatial_correlations, centers_of_bins);
[p_same_centers_of_bins, uncertain_fraction_centroid_distances, ~, false_positive_per_distance_threshold, ...
    true_positive_per_distance_threshold, uncertain_fraction_spatial_correlations, ~, ...
    false_positive_per_correlation_threshold, true_positive_per_correlation_threshold] = ...
    estimate_registration_accuracy(p_same_certainty_threshold, neighbors_centroid_distances, ...
    centroid_distances_model_same_cells, centroid_distances_model_different_cells, ...
    p_same_given_centroid_distance, centers_of_bins, neighbors_spatial_correlations, ...
    spatial_correlations_model_same_cells, spatial_correlations_model_different_cells, ...
    p_same_given_spatial_correlation);
best_model_string = choose_best_model(MSE_centroid_distances_model, centroid_distances_model_same_cells, ...
    centroid_distances_model_different_cells, p_same_given_centroid_distance, MSE_spatial_correlations_model, ...
    spatial_correlations_model_same_cells, spatial_correlations_model_different_cells, ...
    p_same_given_spatial_correlation);
[all_to_all_p_same_centroid_distance_model, all_to_all_p_same_spatial_correlation_model] = ...
    compute_p_same(all_to_all_centroid_distances, p_same_given_centroid_distance, centers_of_bins, ...
    all_to_all_spatial_correlations, p_same_given_spatial_correlation);

if strcmp(best_model_string, 'Spatial correlation')
    if exist('spatial_correlation_intersection', 'var') && ~isempty(spatial_correlation_intersection)
        initial_threshold = spatial_correlation_intersection;
    else
        initial_threshold = 0.65;
    end
    cell_to_index_map = initial_registration_spatial_correlations(normalized_maximal_distance, ...
        initial_threshold, spatial_footprints_corrected, centroid_locations_corrected);
    all_to_all_p_same = all_to_all_p_same_spatial_correlation_model;
else
    if exist('centroid_distance_intersection', 'var') && ~isempty(centroid_distance_intersection)
        initial_threshold = centroid_distance_intersection;
    else
        initial_threshold = 5;
    end
    cell_to_index_map = initial_registration_centroid_distances(normalized_maximal_distance, ...
        initial_threshold / microns_per_pixel, centroid_locations_corrected);
    all_to_all_p_same = all_to_all_p_same_centroid_distance_model;
end
[optimal_cell_to_index_map, ~, cell_scores, ~, ~, ~, p_same_registered_pairs] = ...
    cluster_cells(cell_to_index_map, all_to_all_p_same, all_to_all_indexes, normalized_maximal_distance, ...
    p_same_threshold, centroid_locations_corrected, 'Probabilistic', false);

if use_parallel_processing && ~isempty(gcp('nocreate'))
    delete(gcp('nocreate'));
end
cell_to_index_map = optimal_cell_to_index_map; %#ok<NASGU>
save(out_file, 'cell_to_index_map', 'cell_scores', 'p_same_registered_pairs', 'best_model_string', ...
    'alignment_type', 'alignment_translations', 'p_same_centers_of_bins', ...
    'uncertain_fraction_centroid_distances', 'false_positive_per_distance_threshold', ...
    'true_positive_per_distance_threshold', 'uncertain_fraction_spatial_correlations', ...
    'false_positive_per_correlation_threshold', 'true_positive_per_correlation_threshold', ...
    'centroid_distance_intersection', 'spatial_correlation_intersection', '-v7.3');
end
